def gen_from_templates(templates, subjects, objects=None, n=80):
    data = set()
    for _ in range(n):
        t = random.choice(templates)
        s = random.choice(subjects)
        if objects:
            o = random.choice(objects)
            text = t.format(s, o) if t.count("{}") == 2 else t.format(s)
        else:
            text = t.format(s)
        text = text.replace("  ", "").strip()
        if 4 <= len(text) <= 40:
            data.add(text)
    return data


